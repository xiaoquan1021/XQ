#include "xq_SolverUtils.h"
#include "xq_SolverConfigWriter.h"

#include <fstream>
#include <sstream>

namespace fs = std::filesystem;

namespace xq::solver {

namespace {

void emitFlowHeader(std::ostream& out, const xq_SolverJob& job)
{
    out << "# XQ Simulation Flow File\n"
        << "# Auto-generated by xq::solver\n\n"
        << "job_name: "       << job.GetJobName()       << '\n'
        << "num_timesteps: "  << job.GetNumTimesteps()  << '\n'
        << "timestep_size: "  << job.GetTimeStepSize()  << '\n'
        << "num_cycles: "     << job.GetNumCycles()     << '\n';
}

void emitWallSection(std::ostream& out, const xq_SolverJob& job)
{
    out << "\n# Wall Properties\n"
        << "deformable: "          << (job.GetDeformable() ? "true" : "false") << '\n'
        << "wall_thickness: "      << job.GetWallThickness()      << '\n'
        << "wall_elastic_modulus: " << job.GetWallElasticModulus() << '\n'
        << "wall_density: "        << job.GetWallDensity()        << '\n';
}

void emitSolverSection(std::ostream& out, const xq_SolverJob& job)
{
    out << "\n# Solver Properties\n"
        << "solver_type: "             << job.GetSolverType()             << '\n'
        << "num_linear_iterations: "   << job.GetNumLinearIterations()   << '\n'
        << "num_nonlinear_iterations: " << job.GetNumNonlinearIterations() << '\n';
}

void emitCapPropsBlock(std::ostream& out, std::string_view prefix, const XqSimCapPropertyMap& caps)
{
    if (caps.empty())
        return;
    out << '\n';
    for (const auto& [capName, props] : caps)
    {
        out << '[' << prefix << ':' << capName << "]\n";
        for (const auto& [key, value] : props)
            out << "  " << key << ": " << value << '\n';
    }
}

} // anonymous namespace

fs::path createFlowFile(const xq_SolverJob& job, const fs::path& outputDir)
{
    auto filePath = outputDir / "flow.xqsim";
    std::ofstream ofs(filePath);
    if (!ofs.is_open())
        return {};

    emitFlowHeader(ofs, job);
    emitWallSection(ofs, job);
    emitSolverSection(ofs, job);
    emitCapPropsBlock(ofs, "cap", job.GetCapProps());
    emitCapPropsBlock(ofs, "ic",  job.GetIcProps());

    return filePath;
}

fs::path createSolverInputFile(const xq_SolverJob& job, const fs::path& outputDir)
{
    std::map<std::string, std::string> faceTypes;
    for (const auto& [capName, props] : job.GetCapProps())
    {
        if (auto it = props.find("bc_type"); it != props.end())
            faceTypes[capName] = it->second;
        else
            faceTypes[capName] = "prescribed_velocities";
    }

    constexpr auto kFileName = "solver.xml";

    xq_SolverConfigWriter writer;
    writer.CreateDocument(job, faceTypes, outputDir, kFileName);

    return outputDir / kFileName;
}

fs::path writePresolverScript(const xq_SolverJob& job, const fs::path& outputDir)
{
    auto filePath = outputDir / "presolver.xqpre";
    std::ofstream ofs(filePath);
    if (!ofs.is_open())
        return {};

    ofs << "# XQ Presolver Script\n"
        << "# Auto-generated by xq::solver\n\n"
        << "mesh_and_adjncy_vtu mesh-complete/mesh-complete.mesh.vtu\n\n"
        << "set_surface_id_vtp mesh-complete/walls_combined.vtp 1\n\n";

    int faceId = 2;
    for (const auto& [capName, props] : job.GetCapProps())
    {
        ofs << "set_surface_id_vtp mesh-complete/" << capName << ".vtp " << faceId << '\n';
        ++faceId;
    }
    ofs << '\n';

    if (job.GetDeformable())
    {
        ofs << "deformable_wall\n"
            << "wall_thickness "      << job.GetWallThickness()      << '\n'
            << "wall_elastic_modulus " << job.GetWallElasticModulus() << '\n'
            << "wall_density "        << job.GetWallDensity()        << "\n\n";
    }

    for (const auto& [capName, props] : job.GetIcProps())
    {
        if (auto it = props.find("pressure"); it != props.end())
            ofs << "initial_pressure " << it->second << '\n';
        if (auto it = props.find("velocity"); it != props.end())
            ofs << "initial_velocity " << it->second << '\n';
    }

    ofs << "\nwrite_geombc geombc.dat.1\n"
        << "write_restart restart.0.1\n";

    return filePath;
}

} // namespace xq::solver

// --- Legacy static wrappers ---

std::string xq_SolverUtils::CreateFlowFile(xq_SolverJob* job, const std::string& outputDir)
{
    if (!job) return {};
    return xq::solver::createFlowFile(*job, fs::path(outputDir)).string();
}

std::string xq_SolverUtils::CreateSolverInputFile(xq_SolverJob* job, const std::string& outputDir)
{
    if (!job) return {};
    return xq::solver::createSolverInputFile(*job, fs::path(outputDir)).string();
}

std::string xq_SolverUtils::WritePresolverScript(xq_SolverJob* job, const std::string& outputDir)
{
    if (!job) return {};
    return xq::solver::writePresolverScript(*job, fs::path(outputDir)).string();
}
